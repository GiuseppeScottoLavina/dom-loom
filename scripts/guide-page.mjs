// Wraps a guide page's body (guide/src/<name>.html) in the shared head, bar and layout,
// and writes guide/<name>.html. The first lines of the source are front matter:
//   title: …
//   description: …
//   ---
//   …body (main content)…
//   node scripts/guide-page.mjs            every page
//   node scripts/guide-page.mjs controls   one page
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from '../test/harness.mjs';

const SITE = 'https://giuseppescottolavina.github.io/dom-loom/';
const src = join(root, 'guide/src');
const only = process.argv.slice(2);
const attr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');

for (const file of readdirSync(src).filter((f) => f.endsWith('.html'))) {
  const name = file.replace(/\.html$/, '');
  if (only.length && !only.includes(name)) continue;
  const [front, body] = readFileSync(join(src, file), 'utf8').split(/\n---\n/);
  const meta = Object.fromEntries(front.split('\n').filter(Boolean).map((l) => [l.slice(0, l.indexOf(':')).trim(), l.slice(l.indexOf(':') + 1).trim()]));
  const url = `${SITE}guide/${name === 'index' ? '' : `${name}.html`}`;
  const title = `${meta.title} · DomLoom guide`;
  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${title}</title>
  <meta name="description" content="${attr(meta.description)}">
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="article">
  <meta property="og:site_name" content="DomLoom">
  <meta property="og:title" content="${attr(title)}">
  <meta property="og:description" content="${attr(meta.description)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${SITE}social-preview.png">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="theme-color" content="#0a0e24">
  <link rel="icon" href="../favicon.svg" type="image/svg+xml">
  <link rel="icon" href="../favicon-48.png" sizes="48x48" type="image/png">
  <link rel="apple-touch-icon" href="../apple-touch-icon.png">
  <style>html { background: #0a0e24; color: #e8f4ff; }</style>
  <script type="module" src="./guide.js"></script>
</head>
<body>
  <!-- Generated by scripts/guide-page.mjs from guide/src/${file}: edit the source. -->
  <header class="bar">
    <a class="mark" href="../">Dom<span>Loom</span></a>
    <nav aria-label="Site">
      <a href="../">Demo</a>
      <a href="./">Guide</a>
      <a href="https://github.com/GiuseppeScottoLavina/dom-loom">GitHub</a>
    </nav>
  </header>

  <div class="layout">
    <nav id="guide-nav" aria-label="Guide"></nav>

    <main>
${body.trimEnd()}

      <nav id="guide-pager" aria-label="Pages"></nav>
    </main>
  </div>
</body>
</html>
`;
  writeFileSync(join(root, 'guide', file), html);
  console.log(`guide/${file}`);
}
